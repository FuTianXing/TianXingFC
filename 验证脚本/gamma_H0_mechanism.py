# -*- coding: utf-8 -*-
"""
最小验证（gamma 与落位率的机制性联系）：两条候选机制的判定

背景：gamma <= 1.04e-16 /s 与落位率 3H_0 = 6.81e-18 /s 只差 1.18 个数量级。
本材料判定两条最自然的机制候选是否成立。

判据（先写期望，再算）：
  Y1 落位再退火：若每次落位都扰动记录，则 gamma 约等于落位率。
     结构性核对：框架的插入规则是否扰动记录？
  Y2 膨胀稀释：记录是"每格"读数，共动间隔内的格数随膨胀增长，读数按
     1/a 稀释，稀释率应为 H_0（不是 3H_0）。
  Y3 定量对照：稀释率与观测上界的比，以及它与 3H_0 假设（c_gamma）的关系。
"""
import numpy as np

H0 = 2.2685e-18
G_obs = 1.04e-16

def main():
    print('=' * 76)
    print('gamma 与落位率的机制性联系：两条候选机制的判定')
    print('=' * 76)
    print('[Y1] 落位再退火候选：框架插入规则的结构性核对')
    print('     规则一：新元相子 C 在碰撞点诞生并复刻即将折返者的状态（相位与节律对齐）')
    print('     规则二：让位链的坐标重标是纯标记操作（瞬时、无物理传播）')
    print('     结论：落位不改写记录读数（记录由有质量缺陷的逐拍写入承载，新元相子处于基态 m = 0），')
    print('           故「落位再退火」不成立；该候选被结构性排除。')
    print('[Y2] 膨胀稀释候选：记录按 1/a 稀释，稀释率 = H_0 = %.4e /s（组分数 3 只出现在格点数增长）' % H0)
    print('     注意：稀释作用于共动间隔（宇宙学距离），对束缚系统（固定格数）不作用。')
    print('[Y3] 定量对照：')
    print('     gamma_dil / gamma_obs = %.5f（稀释率比上界低 %.2f 个数量级）'
          % (H0 / G_obs, -np.log10(H0 / G_obs)))
    print('     与 3H_0 假设的关系：c_gamma = gamma/(3H_0)，稀释给 c_gamma = 1/3 = %.4f（在允许区间 c_gamma <= 15.3 内）' % (H0 / (3 * H0)))
    print('     若 gamma 真的取到上界 1.04e-16，则要求 gamma/H_0 = %.1f（O(10) 到 O(100) 档）' % (G_obs / H0))
    print('     判定：量级相容（同一档），机制未闭合（稀释属几何效应，不由介质阻尼通道给出）')

main()
