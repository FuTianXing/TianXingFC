T_START = time.time()

# 体系单位制：l_P = t_P = c = 1
LP = TP = C = 1.0
J = 1.0        # 键刚度（梯度项）
K = 1.0        # 异类耦合（相位差余弦项）
N = 3          # 三元组（公理 2 的三类正交方向）

print('=' * 78)
print('轨道尺度攻坚 阶段 2（第 560 条）：公理 4 是否支持轨道作为驻态')
