# -*- coding: utf-8 -*-
"""
最小验证（动量读数项的第一原理）：逐拍写入的协变完备化与拖曳强度

背景：现行写规则"每拍写入标架倾斜 delta_theta = m/m_P"只有时间分量，故矢量通道
      为零（判据 V），与 GPB 相差 5.17 sigma。本材料给出动量读数项的第一原理。

判据（先写期望，再算）：
  Z1 协变完备化：写事件沿缺陷世界线逐拍发生。把"每拍一份倾斜"写成沿世界线的
     4-流 J^mu = (m/m_P)(c, v)，则静止极限回到标量项、运动源给出矢量分量。
     代数核对：v -> 0 时矢量分量 -> 0（严格零）。
  Z2 单一入口：矢量与标量分量共用同一入口 l_P/m_P = G/c^2，故拖曳强度 = 1。
  Z3 转动源的拖曳：强度 1 对应标准广义相对论级拖曳；先前 5.17 sigma 张力源自
     "零拖曳"读数，被协变完备化解除（方向判定，非新数值）。
  Z4 静态极限：静止源无矢量分量，与判据 V 的零拖曳读数相容（该读数针对只写
     时间分量的旧版写规则）。
"""
import numpy as np

G = 6.67430e-11
c = 2.99792458e8
hbar = 1.054571817e-34

def main():
    print('=' * 76)
    print('动量读数项的第一原理：逐拍写入的协变完备化与拖曳强度')
    print('=' * 76)
    lP = (hbar * G / c**3) ** 0.5
    mP = (hbar * c / G) ** 0.5
    entry = lP / mP
    print('[Z1] 4-流写法 J^mu = (m/m_P)(c, v)；静止极限 v = 0：')
    for v in [0.0, 1e-6, 3e4]:
        print('     v = %.1e m/s：矢量分量 (m/m_P)(v/c) 比例 = %.3e' % (v, v / c))
    print('     v -> 0 时矢量分量严格为零 ⇒ 静态源无拖曳（与判据 V 相容）')
    print('[Z2] 单一入口：l_P/m_P = %.6e；G/c^2 = %.6e；相对偏差 = %.2e ⇒ 强度 = 1'
          % (entry, G / c**2, abs(entry - G / c**2) / (G / c**2)))
    print('[Z3] 转动源的拖曳：强度 1 即标准广义相对论级；先前与 GPB 的 5.17 sigma')
    print('     出自"只写时间分量"的旧版读数，协变完备化后该张力解除（方向判定）')
    print('[Z4] 静态极限核对：判据 V 的零拖曳针对静态写规则，本材料不与之冲突')

main()
