# -*- coding: utf-8 -*-
"""第 11 轮：膨胀问题族条目级关联补全 + 裸引用显式化 + 同族指针。

判据：
- 关联字段只补「正文有明确承接/同题语句」的对偶方向，不制造关联。
- 裸引用「第 N 条」在跨区场景有歧义且不可被引用图谱识别，改为显式编号。
- 同族指针用于让孤立条目（P4-5 零入引）可被从族内发现。
每处替换断言匹配数恰为 1。
"""
import io
import re
import sys

P = '内部草稿/开放问题总览：元相子理论待解决问题清单.md'

raw = open(P, 'rb').read().decode('utf-8')
orig = raw

# (描述, 旧串, 新串)  —— 全部 raw，防 LaTeX 转义撕裂
EDITS = [
    # --- A. 膨胀问题族条目级关联补全 ---
    ('P4-19 关联加 P4-22/P4-30',
     r'《元相子理论的时空观》§2/§9 ｜ 关联：P1-33、P4-20',
     r'《元相子理论的时空观》§2/§9 ｜ 关联：P1-33、P4-20、P4-22、P4-30'),
    ('P4-22 关联加 P4-21',
     r'第十一章内部插入必要性论证 ｜ 关联：P4-19、P4-20',
     r'第十一章内部插入必要性论证 ｜ 关联：P4-19、P4-20、P4-21'),
    ('P4-23 关联加 P4-24',
     r'开放问题 1-3 ｜ 关联：P4-20、P4-21',
     r'开放问题 1-3 ｜ 关联：P4-20、P4-21、P4-24'),
    ('P4-24 关联加 P4-23',
     r'｜ 关联：P4-19、P4-21、P4-25',
     r'｜ 关联：P4-19、P4-21、P4-23、P4-25'),
    ('P4-25 关联加 P4-24/P4-26',
     r'（2026-09-08）｜ 关联：P4-17、P4-21',
     r'（2026-09-08）｜ 关联：P4-17、P4-21、P4-24、P4-26'),
    ('P1-33 关联加 P4-19',
     r'｜ 关联：P1-31、P1-32（已关闭）',
     r'｜ 关联：P1-31、P1-32（已关闭）、P4-19'),

    # --- B. P4-21 开放子项指针化（与 P4-24③、P4-23① 重复登记） ---
    ('P4-21 子项指向 P4-24③',
     r'暴涨 e 折数与持续时间的定量、',
     r'暴涨 e 折数与持续时间的定量（见 P4-24 ③）、'),
    ('P4-21 子项指向 P4-23①',
     r'组分比例仍是观测输入、',
     r'组分比例仍是观测输入（见 P4-23 ①）、'),

    # --- C. 统计力学桥梁链同族指针（P4-5 零入引） ---
    ('P4-5 加同族指针',
     r'5. 系综 → 单粒子投影的概念缺口（来源：《量子力学数学结构的单位圆根基》坦承）',
     r'5. 系综 → 单粒子投影的概念缺口（来源：《量子力学数学结构的单位圆根基》坦承）。'
     r'统计力学桥梁链的同族条目见 P4-13、P4-16。'),
    ('P4-13 加同族指针',
     r'给出候选形式与两界约束。',
     r'给出候选形式与两界约束。统计力学桥梁链的同族条目见 P4-5、P4-16。'),

    # --- D. 裸引用显式化（跨区歧义 + 图谱不可识别） ---
    ('P1-31 裸引用改显式',
     r'内部草稿；承接第 4 条、第 11 条）',
     r'内部草稿；承接 P1-4、P1-11）'),
]

fail = 0
for desc, old, new in EDITS:
    n = raw.count(old)
    if n != 1:
        print(f'FAIL [{desc}] 匹配数={n}（应为 1）')
        fail += 1
        continue
    raw = raw.replace(old, new)
    print(f'OK   [{desc}]')

if fail:
    print(f'\n中止：{fail} 处未应用，文件未写入。')
    sys.exit(1)

# --- 写入前泄漏检查：本批新串内不得含控制字符或转义残留 ---
ctrl = {c for c in raw if ord(c) < 32 and c not in '\r\n\t'}
if ctrl:
    print(f'中止：检出控制字符 {ctrl}')
    sys.exit(1)

# 行尾符守恒
before_crlf = orig.count('\r\n')
after_crlf = raw.count('\r\n')
if before_crlf != after_crlf:
    print(f'中止：CRLF 数变化 {before_crlf} -> {after_crlf}')
    sys.exit(1)

with open(P, 'wb') as f:
    f.write(raw.encode('utf-8'))

print(f'\nOK: {len(EDITS)} 处全部应用')
print(f'字符 {len(orig)} -> {len(raw)}（{len(raw) - len(orig):+d}）')
