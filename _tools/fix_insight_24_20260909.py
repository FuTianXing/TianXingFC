# -*- coding: utf-8 -*-
# 修正核心洞见速览第 24 条（含不换行空格 U+00A0 处理）
import io

p = r'理论总纲\天行新学核心洞见速览.md'
with io.open(p, 'r', encoding='utf-8') as f:
    s = f.read()

old = ('24. 可观测的物理时空是本原通过元相海持续创生而凝固的离散晶格，诞生于多中心局域成核的结晶扩张相变'
       '（大爆炸是多点同时进行，而不是单点爆炸），此后靠边缘缺邻居连续补位向外生长、'
       '靠内部碰撞点离散落位实现均匀膨胀，落位概率\xa03.7\u00d710^63，指数深度139，由边缘几何与宇宙年龄导出，'
       '大爆炸是一次成核事件加一场永续余波。')

new = ('24. 可观测的物理时空是本原持续创生元相子而凝固的离散晶格：诞生于多中心局域成核的结晶扩张相变'
       '（多点独立相继成核，单点爆炸图景废弃），此后靠边缘缺邻居连续补位向外生长、'
       '靠内部碰撞点离散落位实现均匀膨胀，落位概率 $p = 3H_0 t_P \\approx 3.7\\times10^{-61}$（指数深度 139），'
       '由边缘几何与宇宙年龄导出。大爆炸是一次成核事件加一场永续余波。')

assert s.count(old) == 1, 'old 匹配数 = %d' % s.count(old)
s = s.replace(old, new, 1)

with io.open(p, 'w', encoding='utf-8', newline='') as f:
    f.write(s)
print('第 24 条修正完成')
print('em-dash:', s.count('\u2014'), '| Unicode乘号残留:', s.count('\u00d7'), '| 不换行空格残留:', s.count('\xa0'))
